#!/usr/bin/env python3
"""Generates all derived artefacts from components/thermia_bus/catalogue.py.

  components/thermia_bus/registers_gen.cpp  C++ field table used by the core (definitions, one TU)
  docs/REGISTERS.md                        register overview for humans
  config/entities/thermia_entities.yaml    ESPHome entities (packages)

Run from the repository root:  python3 tools/gen.py
Never edit the generated files by hand.
"""
from __future__ import annotations

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "components" / "thermia_bus"))
import catalogue as cat  # noqa: E402

DERIVED_CPP = {
    "CONDENSER_DELTA", "COMPRESSOR_STARTING", "OPERATING_MODE", "HEATING_ACTIVE",
    "DHW_ACTIVE", "COOLING_ACTIVE", "SG_MODE", "CONTROLLER_CONTEXT",
}
KIND_CPP = {
    cat.KIND_NUM: "Kind::NUM", cat.KIND_BIT: "Kind::BIT", cat.KIND_NONZERO: "Kind::NONZERO",
    cat.KIND_SWITCH: "Kind::SWITCH", cat.KIND_EQ: "Kind::EQ", cat.KIND_ENUM: "Kind::ENUM",
    cat.KIND_DERIVED: "Kind::DERIVED",
}


def cfloat(x: float) -> str:
    return f"{float(x)!r}f"


def cpp_entry(idx: int, f: cat.Field) -> tuple[list[str], str]:
    s = f.spec
    enum_lines: list[str] = []
    enum_ref = "nullptr"
    enum_count = 0
    if s.enums:
        name = f"ENUM_{idx}"
        items = ", ".join(f'{{{raw}, "{text}"}}' for raw, text in s.enums)
        enum_lines.append(f"static const EnumEntry {name}[] = {{{items}}};")
        enum_ref = name
        enum_count = len(s.enums)
    valid = s.valid or (0, 0)
    sentinel = s.sentinel if s.sentinel is not None else 0
    derived = f"Derived::{s.derived}" if s.kind == cat.KIND_DERIVED else "Derived::NONE"
    if s.kind == cat.KIND_DERIVED and s.derived not in DERIVED_CPP:
        raise SystemExit(f"unknown derived value {s.derived} for {f.key}")
    space = "Space::READ" if s.space == cat.R else "Space::WRITE"
    row = (
        f'    {{"{f.key}", {KIND_CPP[s.kind]}, {derived}, 0x{s.slave:02X}, {space}, 0x{s.addr:04X}, '
        f'{cfloat(s.div)}, {"true" if s.unsigned else "false"}, {"true" if s.valid else "false"}, '
        f'{cfloat(valid[0])}, {cfloat(valid[1])}, {"true" if s.sentinel is not None else "false"}, '
        f'{sentinel}, 0x{s.mask:04X}, {s.eq}, {enum_ref}, {enum_count}, '
        f'"{s.enum_default}"}},'
    )
    return enum_lines, row


def write_header() -> str:
    lines = [
        "// AUTO-GENERATED by tools/gen.py from components/thermia_bus/catalogue.py. Do not edit.",
        "// Definitions live in a .cpp on purpose: a header would define field_count/field_at in every TU that includes it.",
        '#include "thermia_core.h"',
        "",
        "namespace thermia_core {",
        "namespace gen {",
    ]
    rows: list[str] = []
    for idx, f in enumerate(cat.FIELDS):
        enum_lines, row = cpp_entry(idx, f)
        lines += enum_lines
        rows.append(row)
    lines.append("static const FieldSpec FIELDS[] = {")
    lines += rows
    lines.append("};")
    lines += [
        "}  // namespace gen",
        "",
        "size_t field_count() { return sizeof(gen::FIELDS) / sizeof(gen::FIELDS[0]); }",
        "const FieldSpec& field_at(size_t index) { return gen::FIELDS[index]; }",
        "}  // namespace thermia_core",
        "",
    ]
    return "\n".join(lines)


def write_docs() -> str:
    rows = ["| Gerät | Name (DE) | Quelle auf dem Bus | Art | Standard |", "|---|---|---|---|---|"]
    for f in cat.FIELDS:
        state = "an" if f.enabled_default else "aus"
        rows.append(f"| {cat.DEVICE_LABELS[f.device]} | {f.name_de} | `{f.source}` | {f.kind} | {state} |")
    header = (
        "# Register-Übersicht\n\n"
        "Automatisch erzeugt aus `components/thermia_bus/catalogue.py` (`python3 tools/gen.py`). "
        "Nicht von Hand ändern.\n\n"
        "Quelle der Adressen und Abläufe: ryckema/Thermia_itec, Ordner `Write (Beta)/iTec Eco`.\n\n"
        "Zusätzlich gibt es Diagnose- und Emulationswerte ohne Register: "
        + ", ".join(f"`{k}`" for k, *_ in cat.DIAG_SENSORS) + ".\n\n"
    )
    return header + "\n".join(rows) + "\n"


def check_names() -> None:
    # ESPHome reserves "/" in entity names (URL path separator); it becomes an error in 2027.7.0.
    for f in cat.FIELDS:
        for name in (f"{cat.DEVICE_LABELS[f.device]} {f.name_de}",):
            if "/" in name:
                raise SystemExit(f"entity name contains '/': {name!r}")
    for _key, _kind, name_de, _name_en, _diag, *_metadata in cat.DIAG_SENSORS:
        if "/" in name_de:
            raise SystemExit(f"entity name contains '/': {name_de!r}")


def write_entities() -> str:
    check_names()
    out = [
        "# AUTO-GENERATED by tools/gen.py. Do not edit.",
        "# ESPHome package: all Thermia entities, grouped by device (name prefix).",
        "",
    ]
    by_platform: dict[str, list[str]] = {"sensor": [], "binary_sensor": [], "text_sensor": []}
    for f in cat.FIELDS:
        platform = {"sensor": "sensor", "text": "text_sensor", "binary": "binary_sensor"}[f.kind]
        name = f"{cat.DEVICE_LABELS[f.device]} {f.name_de}"
        block = [
            "  - platform: thermia_bus",
            "    thermia_bus_id: thermia",
            f"    key: {f.key}",
            f'    name: "{name}"',
        ]
        if f.unit:
            block.append(f'    unit_of_measurement: "{f.unit}"')
        if f.device_class:
            block.append(f"    device_class: {f.device_class}")
        if f.state_class:
            block.append(f"    state_class: {f.state_class}")
        if f.diagnostic:
            block.append("    entity_category: diagnostic")
        if not f.enabled_default:
            block.append("    disabled_by_default: true")
        by_platform[platform].append("\n".join(block))
    for key, kind, name_de, _name_en, diagnostic, *metadata in cat.DIAG_SENSORS:
        platform = {"text": "text_sensor", "sensor": "sensor", "binary": "binary_sensor"}[kind]
        block = [
            "  - platform: thermia_bus",
            "    thermia_bus_id: thermia",
            f"    key: {key}",
            f'    name: "{name_de}"',
        ]
        if metadata and metadata[0]:
            block.append(f'    unit_of_measurement: "{metadata[0]}"')
        if diagnostic:
            block.append("    entity_category: diagnostic")
            block.append("    disabled_by_default: true")
        by_platform[platform].append("\n".join(block))
    for platform, blocks in by_platform.items():
        out.append(f"{platform}:")
        out += blocks
        out.append("")
    return "\n".join(out)


def main() -> None:
    (ROOT / "components/thermia_bus/registers_gen.cpp").write_text(write_header(), encoding="utf-8")
    (ROOT / "docs/REGISTERS.md").write_text(write_docs(), encoding="utf-8")
    (ROOT / "config/entities/thermia_entities.yaml").write_text(write_entities(), encoding="utf-8")
    print(f"fields: {len(cat.FIELDS)}, diagnostics: {len(cat.DIAG_SENSORS)}")


if __name__ == "__main__":
    main()
