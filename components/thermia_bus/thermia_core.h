// Protocol core for the Thermia iTec Eco: framing, passive decoder, emulation logic and TX timing.
// Pure C++17, no ESPHome or Arduino dependencies, so it runs on the host for unit tests.
// Timing and behaviour follow ryckema/Thermia_itec, "Write (Beta)/iTec Eco".
#pragma once

#include <cstddef>
#include <cstdint>
#include <deque>
#include <map>
#include <utility>
#include <vector>

namespace thermia_core {

using Bytes = std::vector<uint8_t>;

constexpr uint8_t SLAVE_CONTROLLER = 0x02;
constexpr uint8_t SLAVE_ACCESSORY = 0x06;
constexpr uint8_t SLAVE_ROOM = 0x0A;
constexpr uint8_t SLAVE_DCM = 0x0F;
constexpr uint8_t SLAVE_OUTDOOR = 0x1E;

constexpr uint8_t FC_READ_HOLDING = 0x03;
constexpr uint8_t FC_READ_INPUT = 0x04;
constexpr uint8_t FC_WRITE_MULTIPLE = 0x10;
constexpr uint8_t FC_READ_WRITE = 0x17;

// Timing (microseconds). The repo processes a frame after 5 ms of bus silence and then waits.
constexpr uint32_t TX_SILENCE_US = 5000;
constexpr uint32_t ROOM_TX_PRE_US = 3800;   // 0x0A response
constexpr uint32_t ACK_TX_PRE_US = 5000;    // 0x0F ACK and 0x0708 reply
constexpr uint32_t TX_DE_SETTLE_US = 200;   // DE high before the first byte
constexpr uint32_t TX_HOLD_US = 1200;       // DE low after the last byte was flushed

// Own-echo windows from the repo (milliseconds).
constexpr uint32_t ROOM_OWN_WINDOW_MS = 500;
constexpr uint32_t ACK_OWN_WINDOW_MS = 150;
constexpr int MAX_SETPOINT_RETRIES = 5;

enum class Space : char { READ = 'r', WRITE = 'w' };
enum class Kind : uint8_t { NUM, BIT, NONZERO, SWITCH, EQ, ENUM, DERIVED };
enum class Derived : uint8_t {
  NONE, CONDENSER_DELTA, COMPRESSOR_STARTING, OPERATING_MODE, HEATING_ACTIVE,
  DHW_ACTIVE, COOLING_ACTIVE, SG_MODE, CONTROLLER_CONTEXT
};

struct EnumEntry {
  int32_t raw;
  const char* text;
};

// Positional layout, generated by tools/gen.py.
struct FieldSpec {
  const char* key;
  Kind kind;
  Derived derived;
  uint8_t slave;
  Space space;
  uint16_t addr;
  float div;
  bool is_unsigned;
  bool has_valid;
  float vmin;
  float vmax;
  bool has_sentinel;
  int32_t sentinel;
  uint16_t mask;
  int32_t eq;
  const EnumEntry* enums;
  uint8_t enum_count;
  const char* enum_default;
};

struct Value {
  enum class Type : uint8_t { NONE, NUM, BOOL, TEXT };
  Type type = Type::NONE;
  float num = 0.0f;
  bool b = false;
  const char* text = nullptr;
};

size_t field_count();
const FieldSpec& field_at(size_t index);

// --- CRC and framing -------------------------------------------------------
uint16_t crc16(const uint8_t* data, size_t len);
bool has_valid_crc(const uint8_t* data, size_t len);
Bytes append_crc(const Bytes& payload);

class FrameParser {
 public:
  void feed(const uint8_t* data, size_t len);
  bool pop(Bytes& out);
  void flush();
  uint32_t frames_ok = 0;
  uint32_t resync_bytes = 0;

 private:
  Bytes buf_;
  std::deque<Bytes> frames_;
};

// --- Passive decoder -------------------------------------------------------
struct Reading {
  int16_t value;
  uint32_t t_ms;
};

class PassiveDecoder {
 public:
  void handle(const Bytes& frame, uint32_t now_ms);
  bool get(uint8_t slave, Space space, uint16_t addr, int32_t& out) const;
  uint32_t unmatched_responses = 0;

 private:
  void read_response(uint8_t slave, uint8_t fc, const Bytes& frame, uint32_t now_ms);
  void store(uint8_t slave, Space space, uint16_t start, const uint8_t* data, size_t len, uint32_t now_ms);
  std::map<uint16_t, std::pair<uint16_t, uint16_t>> pending_;  // (slave<<8 | fc) -> (start, count)
  std::map<uint32_t, Reading> registers_;                      // (slave, space, addr) -> value
};

// Evaluates one catalogue field. Returns false if there is no valid value.
bool evaluate(const FieldSpec& field, const PassiveDecoder& decoder, Value& out);

// --- Frame recognition -----------------------------------------------------
bool is_room_poll(const Bytes& frame);
bool is_room_response(const Bytes& frame);
bool parse_fc10_request(const Bytes& frame, uint16_t& start, uint16_t& count);
bool parse_fc03_request(const Bytes& frame, uint16_t& start, uint16_t& count);

// --- Room sensor emulation (0x0A) ------------------------------------------
enum class RoomStatus : uint8_t { DISABLED, WAITING, ACTIVE, TIMEOUT, BLOCKED };
const char* room_status_name(RoomStatus status);

class RoomEmulator {
 public:
  uint32_t watchdog_ms = 30u * 60u * 1000u;  // default 30 min, repo
  bool enabled = false;
  bool has_temp = false;
  float temp = 0.0f;
  uint32_t temp_ms = 0;
  int target = 20;
  int setpoint_request = 0;
  int setpoint_retries = 0;
  int bus_setpoint = -1;
  bool topup_pending = false;
  bool topup_active = false;
  uint32_t responses_sent = 0;
  bool has_last_tx = false;
  uint32_t last_tx_ms = 0;
  bool peer = false;

  RoomStatus status(uint32_t now_ms) const;
  bool set_temperature(float value, uint32_t now_ms);  // only 5..35 degC, strict watchdog
  void clear_temperature();
  int request_setpoint(float value);                   // clamps to 10..30
  void request_topup();
  bool on_poll(uint32_t now_ms, Bytes& out);
  void on_bus_room_response(uint32_t now_ms);
  void on_bus_setpoint(int value);
  void on_bus_topup(int value);
};

// --- 0x0F ACK emulation ----------------------------------------------------
enum class AckStatus : uint8_t { DISABLED, ACTIVE, BLOCKED };

class AckEmulator {
 public:
  bool enabled = false;
  bool peer = false;
  bool has_last_tx = false;
  uint32_t last_tx_ms = 0;
  uint32_t acks_sent = 0;
  uint32_t idle_replies_sent = 0;

  AckStatus status() const;
  void observe_frame(const Bytes& frame, uint32_t now_ms);
  bool on_fc10(uint8_t slave, uint16_t start, uint16_t count, uint32_t now_ms, Bytes& out);
  bool on_fc03(uint8_t slave, uint16_t start, uint16_t count, uint32_t now_ms, Bytes& out);
};

// --- TX timing ---------------------------------------------------------------
// The caller drives the hardware: DE_ON -> set DE high; WRITE -> write_array + flush, then
// call on_written(); DE_OFF -> set DE low.
enum class TxAction : uint8_t { NONE, DE_ON, WRITE, DE_OFF };

class TxScheduler {
 public:
  bool busy() const { return state_ != State::IDLE; }
  bool request(const Bytes& frame, uint32_t due_us);
  TxAction tick(uint32_t now_us);
  void on_written(uint32_t now_us);
  const Bytes& frame() const { return frame_; }

 private:
  enum class State : uint8_t { IDLE, WAIT, SETTLE, WRITE_PENDING, HOLD };
  State state_ = State::IDLE;
  Bytes frame_;
  uint32_t t_ = 0;
  uint32_t due_ = 0;
};

// --- Engine: connects framing, decoder, emulators and TX -------------------
class Engine {
 public:
  FrameParser parser;
  PassiveDecoder decoder;
  RoomEmulator room;
  AckEmulator ack;
  TxScheduler tx;
  uint32_t tx_dropped = 0;

  // Feeds received bytes. now_us: time of reception (microseconds), now_ms: millisecond clock.
  size_t feed(const uint8_t* data, size_t len, uint32_t now_us, uint32_t now_ms);

 private:
  void handle(const Bytes& frame, uint32_t now_us, uint32_t now_ms);
  void schedule(const Bytes& frame, uint32_t pre_us, uint32_t now_us);
  void sync_bus();
};

}  // namespace thermia_core
